-------------------------------------------------------------
-- TRIGGER
-------------------------------------------------------------

CREATE TRIGGER [dbo].[MODIFIEDDATETIME]
   ON  [dbo].[MESSAGEQUEUETABLE]
   AFTER UPDATE
AS 
BEGIN
    SET NOCOUNT ON;

	IF (TRIGGER_NESTLEVEL() > 1) RETURN;

	DECLARE @ID BIGINT;

	SELECT @ID = INSERTED.ID FROM INSERTED;

    UPDATE MESSAGEQUEUETABLE
    SET MODIFIEDDATETIME = SYSDATETIME() 
	WHERE ID = @ID;

END
GO

ALTER TABLE [dbo].[MESSAGEQUEUETABLE] ENABLE TRIGGER [MODIFIEDDATETIME]
GO

