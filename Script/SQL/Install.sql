CREATE  OR ALTER PROCEDURE [dbo].[SPINSERTMESSAGEQUEUE]
(    
   @ENVIRONMENT			VARCHAR(10),
   @SOURCEID			VARCHAR(30),
   @SOURCESYSTEM		VARCHAR(50),  
   @DESTINATIONSYSTEM	VARCHAR(50),
   @TYPE				VARCHAR(50),
   @PAYLOAD				VARCHAR(MAX),   
   @SOURCEENTITY		VARCHAR(20) = '',
   @DESTINATIONID		VARCHAR(30) = '',
   @DESTINATIONENTITY	VARCHAR(20) = '',
   @QUEUE				VARCHAR(50) = '',
   @RESPONSEQUEUE		VARCHAR(50) = '',
   @STATUS				INT = '0'

)
AS
BEGIN
    -- SET NOCOUNT ON added to prevent extra result sets from
    -- interfering with SELECT statements.
    SET NOCOUNT ON

    INSERT INTO MESSAGEQUEUETABLE (ENVIRONMENT,SOURCEID,SOURCESYSTEM, DESTINATIONID, DESTINATIONSYSTEM,
								   TYPE	, PAYLOAD, SOURCEENTITY, DESTINATIONENTITY, STATUS, QUEUE, RESPONSEQUEUE)  
	OUTPUT INSERTED.ID
							VALUES (@ENVIRONMENT,@SOURCEID,@SOURCESYSTEM,@DESTINATIONID, @DESTINATIONSYSTEM,
								   @TYPE, @PAYLOAD, @SOURCEENTITY, @DESTINATIONENTITY, @STATUS, @QUEUE, @RESPONSEQUEUE)

						
END
GO

